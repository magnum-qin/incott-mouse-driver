/** 这个型号代码对应的线稿；没有的返回 null */
const mouseArtFor = (modelCode) => MOUSE_ART[modelCode] ?? null;

const round2 = (n) => Math.round(n * 100) / 100;

/**
 * 小灯和影子摆在哪（画布单位）：灯在机身正中偏手掌的位置，影子在轮廓正下方、宽度是轮廓的 0.44 倍。
 * 比例照着原来那张通用线稿定的（灯在 64% 高度处）；几张画布大小不一样，灯和影子的大小按画布高度算才一致
 */
function artLayout(art) {
  const [x, y, w, h] = art.box;
  const vh = Number(art.viewBox.split(' ')[3]);
  const cx = x + w / 2;
  return {
    led: { cx: round2(cx), cy: round2(y + h * 0.64), r: round2(vh * 0.038) },
    shadow: { cx: round2(cx), cy: round2(y + h + vh * 0.066), rx: round2(w * 0.44), ry: round2(vh * 0.028) },
  };
}

export { MOUSE_ART, mouseArtFor, artLayout };
