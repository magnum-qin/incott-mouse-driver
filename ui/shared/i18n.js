let currentLang = 'zh';

function setLang(lang) {
  if (messages[lang]) currentLang = lang;
  return currentLang;
}

function getLang() {
  return currentLang;
}

function t(key, vars) {
  let s = messages[currentLang][key] ?? messages.zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export { messages, setLang, getLang, t };
